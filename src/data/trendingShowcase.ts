/**
 * Converts a ShowcaseItem into a Movie object so it can be added to the swipe deck
 * or opened in the watch modal / stream finder.
 */
export function showcaseItemToMovie(item: ShowcaseItem): Movie {
  const numericYear = typeof item.year === 'number' ? item.year : parseInt(String(item.year)) || 2026;
  return {
    id: item.id,
    title: item.title,
    poster_path: item.poster_path || null,
    backdrop_path: item.backdrop_path || null,
    media_type: item.type === 'series' ? 'tv' : 'movie',
    year: numericYear,
    runtime: item.runtimeOrSeasons,
    genres: item.genres,
    languages: item.languages,
    imdbRating: item.imdbRating,
    tomatoRating: item.tomatoRating,
    certificate: item.type === 'series' ? 'TV-MA' : 'PG-13',
    director: item.type === 'series' ? 'Showrunners & Creators' : 'Top Director',
    tags: [
      item.viralTag.replace(/^[^\w\s]+/, '').trim(),
      item.categoryLabel,
      item.is2026 ? '2026 New Release' : 'Viral Hit',
    ],
    synopsis: item.synopsis,
    posterUrl: item.poster_path ? `https://image.tmdb.org/t/p/w500${item.poster_path}` : item.posterUrl,
    backdropUrl: item.backdrop_path ? `https://image.tmdb.org/t/p/w1280${item.backdrop_path}` : item.backdropUrl,
    streamingProvidersText: item.streamingOn,
    matchScorePercent: Math.min(99, Math.round(item.imdbRating * 10 + 5)),
    watchLinks: createWatchLinks(item.title, numericYear),
    trailerVideoUrl: item.trailerVideoUrl,
    streamDurationSeconds: 600,
  };
}
